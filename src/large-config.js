/*
 * Cube Music — 大面板（large）运行时配置
 *
 * 在 constants.js 之后、其余脚本之前加载，把 TM.RUNTIME 覆盖成 48 行 × 64 列。
 * **只有 large.html 引入它**；index.html 不加载，因此原版 16×16 逐位不变。
 *
 * 这里只覆盖「与原版不同」的项 —— 没写的（inset / radius / blurCell /
 * 描边参数等）一律自动回落 CONFIG.*。
 */
(function (global) {
  'use strict';

  var TM = global.TM;
  var R = TM.RUNTIME;

  var COLS = 64;                 // 时间步
  var ROWS = 48;                 // 音高行数 = 半音阶 47 个半音（A7 → A#3）
  // 格子边长 = 原版。方块因此是 32 − 2 × 3 = 26px，与原版**逐像素同尺寸**。
  //
  // 代价是画布变成 64×48 × 32px = 2048 × 1536：既超出笔记本横向视口，
  // 也远超其纵向视口（48 行 × 26px 光棋盘就有 1536px 高）。这是几何决定的，
  // 想同时要「大盘面」和「原版大小的方块」就必然要滚动 —— 所以布局改成
  // 不缩放、可滚动（见 style.css 的 body.wide / .stage-wide），
  // 方块保持 1:1 上屏，浏览器不做二次重采样。
  //
  // 曾经试过把格子减半到 16px 来塞进屏幕，但那样按比例算出的内缩是 1.5，
  // 在 1x 屏上方块边界落在半像素、被抗锯齿糊出灰边（实测过渡值 25 / 119，
  // 整数内缩下灰度只出现 0 / 51 / 238 三个值）。既然要跟原版一样大，
  // 索性连格子尺寸一起沿用原版，这条坑也就不存在了。
  var CELL = TM.CONFIG.CELL;

  // 面板身份。**注意它不带尺寸** —— 存档键是 cubemusic.score.large，
  // 以后再加/减八度，键不变，用户存在本机的那份谱子会自动接着用。
  R.id = 'large';
  R.cols = COLS;
  R.rows = ROWS;
  R.cell = CELL;

  // ── 音阶：半音阶（相邻行差 1 个半音，像吉他每格一品）──
  // 48 行覆盖 47 个半音（将近 4 个八度）：行 0 = A7 = 原版最高音再高一个八度，
  // 往下一直铺到 A#3。原版 16 行的音域（A6 → A3）几乎完整落在这张表里，
  // 只是把中间的音填满了 —— 中段仍与原版的中音区重合。
  //
  // 往上加一个八度 = TOP + 12、ROWS + 12，**底部不动**，
  // 所以旧表（96..61）正好落在新表的行 12..47。
  var TOP = TM.CONFIG.NOTES[0] + 12;       // 108 = A7（原版最高音 + 一个八度）
  R.notes = TM.buildScaleTable(ROWS, TOP, TM.SCALES.chromatic);   // A7 → A#3

  // 注意：原版 16 行是五声、这里是半音阶，所以**没有「行号平移对应」关系** ——
  // 同一份图案搬过来音高会变。但半音阶是任何音阶的超集：原版每个音都能在这张
  // 表里找到（只是行号不同），test/large.html 有断言守着这条。

  // ── 波纹 ───────────────────────────────────────────────
  // 波纹层**刻意低于画布分辨率**：1024 × 768（画布是 2048 × 1536），合成时放大 2×。
  // 它本来就要被大半径模糊，按画布分辨率渲染纯属浪费面积。
  //
  // blurWave = 6：这里一个波纹格 = 1024 / 64 = 16px，原版是 512 / 16 = 32px、
  // 模糊 12。取 16 × 12/32 = 6，两版的涟漪相对网格的柔和程度就一致。
  R.waveSize = 1024;
  R.blurWave = 6;

  // ── 布局 ───────────────────────────────────────────────
  // 画布的 CSS 尺寸 = 逻辑尺寸（不是设备尺寸），这样无论 dpr 多少都是 1:1 上屏。
  // 写成 CSS 变量给 style.css 用，避免在样式表里硬编码 2048 / 1024。
  var root = global.document.documentElement;
  root.style.setProperty('--board-w', (COLS * CELL) + 'px');
  root.style.setProperty('--board-h', (ROWS * CELL) + 'px');
})(window);
