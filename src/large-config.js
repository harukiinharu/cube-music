/*
 * Cube Music — 大面板（large）运行时配置
 *
 * 在 constants.js 之后、其余脚本之前加载，把 TM.RUNTIME 覆盖成 32 行 × 64 列。
 * **只有 large.html 引入它**；index.html 不加载，因此原版 16×16 逐位不变。
 *
 * 这里只覆盖「与原版不同」的项 —— 没写的（inset / radius / blurCell /
 * 描边参数等）一律自动回落 CONFIG.*。
 */
(function (global) {
  'use strict';

  var TM = global.TM;
  var R = TM.RUNTIME;

  var COLS = 64;                 // 时间步
  var ROWS = 32;                 // 音高行数
  // 格子边长 = 原版。方块因此是 32 − 2 × 3 = 26px，与原版**逐像素同尺寸**。
  //
  // 代价是画布变成 64×32 × 32px = 2048 × 1024：既超出笔记本横向视口，
  // 也超出其纵向视口（32 行 × 26px 光棋盘就有 1024px 高）。这是几何决定的，
  // 想同时要「大盘面」和「原版大小的方块」就必然要滚动 —— 所以布局改成
  // 不缩放、可滚动（见 style.css 的 body.wide / .stage-wide），
  // 方块保持 1:1 上屏，浏览器不做二次重采样。
  //
  // 曾经试过把格子减半到 16px 来塞进屏幕，但那样按比例算出的内缩是 1.5，
  // 在 1x 屏上方块边界落在半像素、被抗锯齿糊出灰边（实测过渡值 25 / 119，
  // 整数内缩下灰度只出现 0 / 51 / 238 三个值）。既然要跟原版一样大，
  // 索性连格子尺寸一起沿用原版，这条坑也就不存在了。
  var CELL = TM.CONFIG.CELL;

  R.cols = COLS;
  R.rows = ROWS;
  R.cell = CELL;

  // ── 音阶：D 大调七声（五声补上第 4 音 G 与第 7 音 C#）──
  // 行 0 取原版最高音再高 7 个半音（A6 + 7 = E7），这样 32 行跨 53 个半音的
  // 中段落在 D5 / C#5 附近，与原版 16 行（中段 E5 / D5）基本对齐。
  var TOP = TM.CONFIG.NOTES[0] + 7;        // 103 = E7
  R.notes = TM.buildScaleTable(ROWS, TOP, TM.SCALES.major);   // E7 → B2，约 4.4 个八度

  // 注意：原版 16 行是五声、这里是七声，所以**不再有「中间若干行与原版逐位相同」
  // 那种平移对应关系**了。但七声是五声的超集 —— 原版每个音都能在这张表里找到
  // （只是行号不同），test/large.html 有断言守着这条。

  // ── 波纹 ───────────────────────────────────────────────
  // 波纹层**刻意低于画布分辨率**：1024 × 512（画布是 2048 × 1024），合成时放大 2×。
  // 它本来就要被大半径模糊，按画布分辨率渲染纯属浪费面积。
  //
  // blurWave = 6：这里一个波纹格 = 1024 / 64 = 16px，原版是 512 / 16 = 32px、
  // 模糊 12。取 16 × 12/32 = 6，两版的涟漪相对网格的柔和程度就一致。
  R.waveSize = 1024;
  R.blurWave = 6;

  // ── 布局 ───────────────────────────────────────────────
  // 画布的 CSS 尺寸 = 逻辑尺寸（不是设备尺寸），这样无论 dpr 多少都是 1:1 上屏。
  // 写成 CSS 变量给 style.css 用，避免在样式表里硬编码 2048 / 1024。
  var root = global.document.documentElement;
  root.style.setProperty('--board-w', (COLS * CELL) + 'px');
  root.style.setProperty('--board-h', (ROWS * CELL) + 'px');
})(window);
